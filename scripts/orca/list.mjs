import { open, startOrca, mark, key, keys, type, finish, sleep } from './lib.mjs';
import { seed } from './seed.mjs';
const page = await open();
const id = await seed(page);
await page.goto(`http://localhost:5174/#/view/${id}`); await sleep(2500);
await startOrca('list');
mark('Tab x2 to list button, Enter'); await keys(['Tab','Tab']); await key('Return', 3000);
mark('Tab x5 in list'); await keys(Array(5).fill('Tab'), 900);
mark('browse mode: Down x12 from list top (Orca browse)'); await key('Insert+a', 500);
await page.evaluate(() => document.querySelector('[data-testid=floor-list]')?.focus()); await sleep(1500);
await keys(Array(12).fill('Down'), 700);
mark('H in list (next heading)'); await keys(['h','h','h']);
mark('Tab to a list item, Enter'); await page.evaluate(() => document.querySelectorAll('[data-testid=list-item]')[3]?.focus()); await sleep(1500); await key('Return', 3000);
mark('Escape on card'); await key('Escape', 2000);
mark('Floor 2 button press'); await page.evaluate(() => document.querySelector('[data-testid="viewer-floor-Floor 2"]')?.focus()); await sleep(1200); await key('Return', 2500);
mark('search no match'); await page.evaluate(() => document.querySelector('[data-testid=viewer-search]')?.focus()); await sleep(1200); await type('zzz', 2500);
mark('Enter in search'); await key('Return', 2500);
mark('clear search; type 2B5 + Enter'); await key('ctrl+a', 300); await key('BackSpace', 1000); await type('2B5', 1500); await key('Return', 3000);
mark('Directions, start, then Escape inside panel');
await page.evaluate(() => document.querySelector('[data-testid=directions]')?.focus()); await sleep(1000); await key('Return', 2500);
await page.evaluate(() => document.querySelector('[data-testid=dir-start]')?.focus()); await sleep(1200); await key('Return', 3500);
await keys(['Tab','Tab'], 1000);
await key('Escape', 2500);
mark('after Escape: Tab'); await key('Tab');
await finish('out/list.txt');
